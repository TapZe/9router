/**
 * Writes open-sse/providers/factoryDroid.js from a Factory Droid registry extract.
 *
 * The extract is a JSON object keyed by model id. Each row holds what the Droid
 * binary computes for that model, with "off" for its off or none effort. It is
 * made offline from the binary, with no login and no Factory API calls.
 *
 * Run: node scripts/gen-factory-droid.mjs <droid-models.json> <droid-version>
 */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = path.join(ROOT, "open-sse/providers/factoryDroid.js");
// Request bodies live in their own file so dashboard pages that read model
// facts do not ship them to the browser.
const REQUESTS_OUT = path.join(ROOT, "open-sse/providers/factoryDroidRequests.js");
const ORDER = ["none", "minimal", "low", "medium", "high", "xhigh", "max"];
// Droid 1.3.0 runs a model it does not offer on its default model, the first
// of its default list (Be, "gpt-6.1-sol", in the bundle).
const DEFAULT_MODEL = "gpt-6.1-sol";
// Ids 9router offered before Droid 1.3.0 dropped them.
const RETIRED_MODELS = ["gpt-5", "gpt-5.1", "gpt-5-codex", "gpt-5.1-codex"];

const [input, version] = process.argv.slice(2);
if (!input || !version) {
  console.error("Usage: node scripts/gen-factory-droid.mjs <droid-models.json> <droid-version>");
  process.exit(2);
}

// 9router names the off effort "none".
const effortName = (effort) => (effort === "off" ? "none" : effort);

// Each provider's request bodies, keyed by 9router's effort names.
function requestsOf(model) {
  return Object.fromEntries(Object.entries(model.requests).map(([provider, byEffort]) => [
    provider,
    Object.fromEntries(Object.entries(byEffort).map(([effort, request]) => [effortName(effort), request])),
  ]));
}

function row(model) {
  return {
    api: model.api,
    efforts: model.efforts.map(effortName).sort((a, b) => ORDER.indexOf(a) - ORDER.indexOf(b)),
    defaultEffort: effortName(model.defaultEffort),
    images: model.images,
    maxInputTokens: model.maxInputTokens,
    maxOutputTokens: model.maxOutputTokens,
    providers: model.providers,
  };
}

const models = JSON.parse(fs.readFileSync(input, "utf8"));
const lines = Object.keys(models).sort().map((id) => `  ${JSON.stringify(id)}: ${JSON.stringify(row(models[id]))},`);

fs.writeFileSync(OUT, `// Generated by scripts/gen-factory-droid.mjs from the Factory Droid ${version} binary. Do not edit by hand.
//
// Each row holds what Droid ${version} uses for one model. That is the reasoning
// efforts it accepts, the effort it uses by default, whether it takes images,
// its input and output token limits, and the provider it picks in each
// inference region. "none" is the off effort.
export const FACTORY_DROID_VERSION = ${JSON.stringify(version)};

export const FACTORY_DROID_MODELS = {
${lines.join("\n")}
};

// Droid ${version} runs a model it does not offer on its default model. These
// are the ids 9router offered before Droid dropped them.
export const FACTORY_DROID_DEFAULT_MODEL = ${JSON.stringify(DEFAULT_MODEL)};
export const FACTORY_DROID_RETIRED_MODELS = ${JSON.stringify(RETIRED_MODELS)};

// The model Droid runs for an id.
export function factoryDroidModelId(id) {
  return FACTORY_DROID_RETIRED_MODELS.includes(id) ? FACTORY_DROID_DEFAULT_MODEL : id;
}
`);
const requestLines = Object.keys(models).sort().map((id) => `  ${JSON.stringify(id)}: ${JSON.stringify(requestsOf(models[id]))},`);
fs.writeFileSync(REQUESTS_OUT, `// Generated by scripts/gen-factory-droid.mjs from the Factory Droid ${version} binary. Do not edit by hand.
//
// For each model, the body fields and Anthropic betas Droid ${version} sends
// for each provider and effort. "none" is the off effort, and "$session" is
// filled with the session id at request time.
export const FACTORY_DROID_REQUESTS = {
${requestLines.join("\n")}
};
`);
console.log(`Wrote ${Object.keys(models).length} models to ${path.relative(ROOT, OUT)}`);
